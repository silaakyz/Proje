/** Every section name the API accepts (unchanged request contract). */
export const ALL_BLUEPRINT_SECTIONS = ["registration", "tasks", "kpis", "budget_risks", "surveys"] as const;
export type BlueprintSection = (typeof ALL_BLUEPRINT_SECTIONS)[number];
/** Generated by default. Surveys follow KPIs. */
export const SUPPORTED_SECTIONS = ["tasks", "kpis", "surveys"] as const satisfies readonly BlueprintSection[];
/** No Drizzle tables for their operations yet: never generated. */
export const UNSUPPORTED_SECTIONS = ["registration", "budget_risks"] as const satisfies readonly BlueprintSection[];
export type SectionStatus = "ok" | "unsupported" | string;

/** Proposals stay applicable for 14 days. */
const PROPOSAL_TTL_MS = 14 * 86_400_000;

export interface SectionRunContext {
  org: OrgAccess;
  eventId: string;
  today: string;
}

/** Refuses a request that names an unsupported section (INVALID → HTTP 422). */
export function assertSectionsSupported(sections: readonly string[]) {
  const unsupported = sections.filter((s) => (UNSUPPORTED_SECTIONS as readonly string[]).includes(s));
  if (unsupported.length)
    throw new ProposalError(
      "INVALID",
      `Desteklenmeyen bölüm: ${unsupported.join(", ")}. Bu bölümler henüz uygulanamadığı için üretilmiyor.`,
    );
}

/**
 * Persists a PENDING proposal linked to its generation. Refuses (and stores nothing) when the operations
 * fail the Zod contract or contain anything the apply service cannot apply.
 */
export async function saveProposal(ctx: SectionRunContext | { org: OrgAccess; eventId: null }, generationId: string, p: ProposalDraft) {
  const operations = proposalOperationsSchema.parse(p.operations); // ZodError: nothing stored
  assertOperationsSupported(operations.map((op, index) => ({ op, index }))); // ProposalError INVALID: nothing stored

  let baseVersion: string | null = null;
  if (ctx.eventId) {
    const [ev] = await adminDb
      .select({ updatedAt: events.updatedAt })
      .from(events)
      .where(and(eq(events.id, ctx.eventId), eq(events.organizationId, ctx.org.organizationId)))
      .limit(1);
    if (!ev) throw new ProposalError("NOT_FOUND", "Event not in organization");
    baseVersion = ev.updatedAt.toISOString();
  }
  const payload = { operations: p.operations };
  const [row] = await adminDb
    .insert(proposals)
    .values({
      organizationId: ctx.org.organizationId,
      eventId: ctx.eventId,
      generationId, // composite FK: must be a generation of the same organization
      requestedBy: ctx.org.userId,
      kind: p.kind,
      title: p.title,
      rationale: p.rationale,
      payload,
      aiFingerprint: fingerprint(payload),
      schemaVersion: BLUEPRINT_SCHEMA_VERSION,
      baseVersion,
      expiresAt: new Date(Date.now() + PROPOSAL_TTL_MS),
    })
    .returning({ id: proposals.id });
  return row!;
}

/**
 * Stage 1 completion, called after the streamed response finished. Any failure is recorded on the
 * generation and produces NO proposal. A valid profile becomes a PENDING proposal.
 */
export async function finalizeCoreGeneration(args: {
  org: OrgAccess;
  generationId: string;
  today: string;
  startedAt: number;
  organizerModules?: readonly ModuleKey[];
  output: () => Promise<unknown>;
  usage: () => Promise<{ inputTokens?: number; outputTokens?: number }>;
  /** Same request on the fallback model, tried once when the main model fails in a way another model may not. */
  fallback?: () => Promise<{ output: unknown; usage: { inputTokens?: number; outputTokens?: number } }>;
}): Promise<{ status: "PROPOSED" | "FAILED_VALIDATION" | "FAILED_PROVIDER"; proposalId?: string }> {
  const latency = () => Date.now() - args.startedAt;
  let raw: unknown;
  let usage: () => Promise<{ inputTokens?: number; outputTokens?: number }> = args.usage;
  let fallbackUsed: { model: string; after: AiFailure } | null = null;
  try {
    raw = await args.output();
  } catch (err) {
    const first = classifyAiError(err);
    let second: AiFailure | null = null;
    if (args.fallback && first.retryWithFallback) {
      try {
        const r = await args.fallback();
        raw = r.output;
        usage = () => Promise.resolve(r.usage);
        fallbackUsed = { model: FALLBACK_MODEL_ID, after: first };
      } catch (err2) {
        second = classifyAiError(err2);
      }
    }
    if (!fallbackUsed) {
      // The last failure decides what the organizer is told; both are kept for diagnosis.
      const last = second ?? first;
      await finishGeneration(args.org, args.generationId, {
        status: "FAILED_PROVIDER",
        errors: { message: last.message, kind: last.kind, status: last.status ?? null, attempts: second ? [first, { ...second, model: FALLBACK_MODEL_ID }] : [first] },
        latencyMs: latency(),
      });
      return { status: "FAILED_PROVIDER" };
    }
  }
  // Re-parse even though the SDK validated it: this function must not trust its caller.
  const draft = blueprintCoreDraftSchema.safeParse(raw);
  if (!draft.success) {
    await finishGeneration(args.org, args.generationId, {
      status: "FAILED_VALIDATION", output: raw, errors: z.treeifyError(draft.error), latencyMs: latency(),
    });
    return { status: "FAILED_VALIDATION" };
  }
  const n = normalizeBlueprintCore(draft.data, {
    today: args.today, organizationType: args.org.organizerType, organizerModules: args.organizerModules,
  });
  if (!n.ok) {
    await finishGeneration(args.org, args.generationId, {
      status: "FAILED_VALIDATION", output: { draft: draft.data, partial: n.partial, repairs: n.repairs },
      errors: z.treeifyError(n.error), latencyMs: latency(),
    });
    return { status: "FAILED_VALIDATION" };
  }
  const used = await usage().catch(() => ({}) as { inputTokens?: number; outputTokens?: number });
  await finishGeneration(args.org, args.generationId, {
    status: "SUCCEEDED", output: { draft: draft.data, core: n.core, repairs: n.repairs, ...(fallbackUsed ? { fallback: fallbackUsed } : {}) },
    inputTokens: used.inputTokens, outputTokens: used.outputTokens, latencyMs: latency(),
  });
  const p = await saveProposal({ org: args.org, eventId: null }, args.generationId, coreProposal(n.core));
  return { status: "PROPOSED", proposalId: p.id };
}

/** One structured-output call with full audit. Throws on provider error after recording it. */
async function runStructured<S extends z.ZodType>(
  ctx: SectionRunContext,
  kind: string,
  schema: S,
  system: string,
  prompt: string,
): Promise<{ generationId: string; output: z.infer<S> }> {
  const task = AI_TASKS.eventBuilder;
  const startedAt = Date.now();
  const generationId = await startGeneration(ctx.org, {
    eventId: ctx.eventId, kind, prompt, schemaVersion: kind, provider: task.provider, model: task.modelId, temperature: task.temperature,
  });
  const call = (fallback: boolean) => generateText({
    model: modelFor("eventBuilder", { fallback }),
    temperature: task.temperature,
    maxOutputTokens: task.maxOutputTokens,
    system,
    prompt,
    output: Output.object({ schema }),
    ...(fallback ? {} : { providerOptions: structuredProviderOptions() }),
  });
  try {
    let result;
    try {
      result = await call(false);
    } catch (first) {
      // One more try on the fallback model when another model may succeed (busy, quota, cut-off output …).
      if (!classifyAiError(first).retryWithFallback) throw first;
      result = await call(true);
    }
    await finishGeneration(ctx.org, generationId, {
      status: "SUCCEEDED", output: result.output, latencyMs: Date.now() - startedAt,
      inputTokens: result.totalUsage.inputTokens, outputTokens: result.totalUsage.outputTokens,
    });
    return { generationId, output: result.output as z.infer<S> };
  } catch (err) {
    // Output that does not match the schema is a validation failure, not a provider outage.
    const invalid = NoObjectGeneratedError.isInstance(err);
    await finishGeneration(ctx.org, generationId, {
      status: invalid ? "FAILED_VALIDATION" : "FAILED_PROVIDER",
      output: invalid ? { text: (err as InstanceType<typeof NoObjectGeneratedError>).text ?? null } : undefined,
      errors: (() => { const f = classifyAiError(err); return { message: f.message, kind: f.kind, status: f.status ?? null }; })(),
      latencyMs: Date.now() - startedAt,
    });
    throw err;
  }
}

/** The approved core from events.ai_config (organization-scoped); the event row's dates win. */
export async function loadApprovedCore(organizationId: string, eventId: string): Promise<BlueprintCore> {
  const [event] = await adminDb
    .select({ aiConfig: events.aiConfig, startDate: events.startDate, endDate: events.endDate })
    .from(events)
    .where(and(eq(events.id, eventId), eq(events.organizationId, organizationId)))
    .limit(1);
  if (!event) throw new ProposalError("NOT_FOUND", "Event not in organization");
  const core = blueprintCoreSchema.parse(event.aiConfig);
  // The organizer may have edited dates after approving; the DB row wins.
  core.event.startDate = event.startDate;
  core.event.endDate = event.endDate;
  return core;
}

/**
 * Runs the supported section stages after the core is applied. Tasks and KPIs run in parallel; surveys
 * wait for KPIs because KPI choice decides the canonical questions. Each finished section becomes its
 * own proposal card, so one failure never blocks the rest.
 *
 * Status per section: "ok", "unsupported" (default run only, for sections that are never generated), or
 * the error message. Naming an unsupported section explicitly throws INVALID before any work.
 */
export async function runBlueprintSections(
  ctx: SectionRunContext,
  sections?: readonly BlueprintSection[],
): Promise<Record<string, SectionStatus>> {
  if (sections) assertSectionsSupported(sections);
  const want = new Set<BlueprintSection>(sections ?? SUPPORTED_SECTIONS);
  const status: Record<string, SectionStatus> = {};
  if (!sections) for (const s of UNSUPPORTED_SECTIONS) status[s] = "unsupported";

  const core = await loadApprovedCore(ctx.org.organizationId, ctx.eventId);
  const modules = core.modules.map((m) => m.key);
  const vocab = vocabularyFor(modules);
  const sys = (s: Parameters<typeof buildSectionSystemPrompt>[0], extra: Partial<Parameters<typeof buildSectionSystemPrompt>[1]> = {}) =>
    buildSectionSystemPrompt(s, { today: ctx.today, orgName: ctx.org.organizationName, core, ...extra });
  const go = "Bu etkinlik profili için bu bölümü hazırla.";
  const track = async (name: string, fn: () => Promise<void>) => {
    try {
      await fn();
      status[name] = "ok";
    } catch (e) {
      status[name] = e instanceof Error ? e.message : String(e);
    }
  };

  const jobs: Promise<void>[] = [];

  if (want.has("tasks"))
    jobs.push(track("tasks", async () => {
      const { generationId, output } = await runStructured(ctx, "blueprint.tasks", buildTasksDraftSchema(vocab.workstreams), sys("tasks"), go);
      const r = normalizeTasks(output, core);
      await saveProposal(ctx, generationId, tasksProposal(r.tasks, r.warnings));
    }));

  if (want.has("kpis") || want.has("surveys"))
    jobs.push(track("kpis", async () => {
      const candidates = candidateMetrics(core.event.format, modules);
      const { generationId, output } = await runStructured(
        ctx, "blueprint.kpis", buildKpisDraftSchema(candidates.map((c) => c.key)), sys("kpis", { candidates }), go,
      );
      const k = normalizeKpis(output, core);
      const req = deriveDataRequirements(k.kpis);
      const measurement = deriveMeasurementTasks(req, core);
      // No metric_definitions table: every library definition is unreviewed until the literature review
      // (METRIC_LIBRARY header), so no evidence is passed and the card says so.
      const proposal = kpisProposal(k.kpis, k.warnings, {});
      proposal.operations.push(...measurement.map((data) => ({ op: "upsert" as const, entity: "task" as const, data })));
      proposal.title = `${k.kpis.length} KPI ve ${measurement.length} ölçüm görevi`;
      await saveProposal(ctx, generationId, proposal);

      if (want.has("surveys"))
        await track("surveys", async () => {
          const audiences = surveyAudiencesFor(core, req);
          if (!audiences.length) return;
          const s = await runStructured(ctx, "blueprint.surveys", buildSurveysDraftSchema(audiences), sys("surveys", { audiences }), go);
          const r = normalizeSurveys(s.output, core, k.kpis, req);
          if (r.surveys.length) await saveProposal(ctx, s.generationId, surveysProposal(r.surveys));
        });
    }));

  await Promise.all(jobs);
  return status;
}
