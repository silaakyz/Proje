/**
 * AI Blueprint service on the Drizzle data model: prompts, Zod schemas and normalizers from src/lib/ai.
 *
 *  - Stage 1 (core profile) → a PENDING `blueprint.core` proposal. Nothing is applied automatically.
 *  - Stage 2 (sections) → one PENDING proposal per section.
 *
 * Unsupported sections: `registration` (ticket types, form fields) and `budget_risks` (budget lines,
 * risks) have no Drizzle tables yet, so their proposals could never be applied. They are not generated
 * (no LLM cost, no card the organizer cannot apply); asking for them explicitly is refused with INVALID,
 * and a default run reports them as "unsupported" in the section status.
 *
 * Security: callers pass the verified OrgAccess (requireOrgPermission(org, "blueprint.generate")).
 * Writes go through adminDb and every statement is scoped by organization_id; composite FKs back that up.
 */
